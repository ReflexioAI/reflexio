// Regenerate src/generated/openapi.ts from the Reflexio server's OpenAPI
// document, so the client's request and response types are the server's own
// rather than a hand-kept copy.
//
//   npm run generate          rewrite the file
//   npm run check-generated   exit 1 if the committed file is stale (CI)
//
// Needs the Python package's environment (`uv sync` at the repo root): the
// document comes from the FastAPI app itself, not from a running server.

import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";

const pkg = join(dirname(fileURLToPath(import.meta.url)), "..");
const target = join(pkg, "src", "generated", "openapi.ts");

const schema = JSON.parse(
  execFileSync(
    "uv",
    [
      "run",
      "--no-sync",
      "python",
      "-c",
      "import json; from reflexio.server.api import app; print(json.dumps(app.openapi()))",
    ],
    { cwd: join(pkg, ".."), encoding: "utf8", maxBuffer: 64 * 1024 * 1024 },
  ),
);

// Fields with a server-side default stay optional: a caller of the client
// should not have to restate every default to build a request.
const ast = await openapiTS(schema, { defaultNonNullable: false });
const header = [
  "// Generated by scripts/generate-types.mjs from the Reflexio server's OpenAPI",
  "// document. Do not edit by hand; run `npm run generate`.",
  "",
].join("\n");
const contents = `${header}${astToString(ast)}`;

if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(target, "utf8");
  } catch {}
  if (current !== contents) {
    console.error(`${target} is stale. Run \`npm run generate\` in client_ts/ and commit the result.`);
    process.exit(1);
  }
  console.log("generated types are current");
} else {
  writeFileSync(target, contents);
  console.log(`wrote ${target}`);
}
